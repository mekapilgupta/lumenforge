      attributes: {},
      size_stock: sizeStock,
      price_override: '',
      compare_at_price: '',
      stock_quantity: productForm.sizes.length * 10,
      is_default: variants.length === 0,
      position: variants.length,
      images: []
    };

    variants = [...variants, newVariant];
    activeVariantTabId = newVariant.id!;
  }

  function duplicateVariant(index: number) {
    const src = variants[index];
    const nextColor = QUICK_PALETTE[(index + 1) % QUICK_PALETTE.length];
    const slugCode = (productForm.slug || 'FT').toUpperCase().slice(0, 8);
    const colorCode = slugify(nextColor.name).toUpperCase().slice(0, 4);
    const newSku = `${slugCode}-${colorCode}-${variants.length + 1}`;

    const cloned: LocalVariant = {
      id: crypto.randomUUID(),
      sku: newSku,
      color_name: nextColor.name,
      color_slug: slugify(nextColor.name),
      color_hex: nextColor.hex,
      attributes: JSON.parse(JSON.stringify(src.attributes || {})),
      size_stock: JSON.parse(JSON.stringify(src.size_stock || {})),
      price_override: src.price_override,
      compare_at_price: src.compare_at_price,
      stock_quantity: src.stock_quantity,
      is_default: false, // Clone is never default
      position: variants.length,
      images: [] // images are not duplicated per requirements
    };

    variants = [...variants, cloned];
    activeVariantTabId = cloned.id!;
    uiStore.addToast(`Duplicated "${src.color_name}" as "${cloned.color_name}"`, 'info');
  }

  function removeVariant(index: number) {
    if (variants.length <= 1) {
      uiStore.addToast('A product must have at least one color variant.', 'error');
      return;
    }

    const removed = variants[index];
    const remaining = variants.filter((_, i) => i !== index);

    // If we removed the default variant, assign the first remaining one as default
    if (removed.is_default && remaining.length > 0) {
      remaining[0].is_default = true;
    }

    variants = remaining;
    if (activeVariantTabId === removed.id && variants.length > 0) {
      activeVariantTabId = variants[0].id!;
    }
    uiStore.addToast(`Removed variant "${removed.color_name}"`, 'info');
  }

  function setDefaultVariant(index: number) {
    variants = variants.map((v, i) => ({
      ...v,
      is_default: i === index
    }));
  }

  // Ensure DB record exists so images can be attached via foreign keys
  async function ensureDraftInDatabase(): Promise<boolean> {
    if (!productForm.name || !productForm.slug) {
      uiStore.addToast('Please enter product name and slug first.', 'error');
      currentStep = 1;
      return false;
    }

    if (!productForm.id) {
      productForm.id = crypto.randomUUID();
    }

    try {
      const payload = {
        product: {
          id: productForm.id,
          name: productForm.name,
          slug: productForm.slug,
          brand: productForm.brand,
          category: productForm.category,
          base_price: parseFloat(productForm.base_price) || 0,
          compare_at_price: productForm.compare_at_price ? parseFloat(productForm.compare_at_price) : null,
          sizes: productForm.sizes,
          description: productForm.description,
          status: 'draft' // ensure draft during image uploads
        },
        variants: variants.map((v, i) => ({
          id: v.id || crypto.randomUUID(),
          sku: v.sku || `${productForm.slug.toUpperCase()}-${i}`,
          color_name: v.color_name,
          color_slug: v.color_slug || slugify(v.color_name),
          color_hex: v.color_hex,
          attributes: { ...v.attributes, size_stock: v.size_stock },
          price_override: v.price_override ? parseFloat(String(v.price_override)) : null,
          compare_at_price: v.compare_at_price ? parseFloat(String(v.compare_at_price)) : null,
          stock_quantity: v.stock_quantity || 0,
          is_default: v.is_default,
          position: i
        }))
      };

      const res = await fetch('/api/admin/products/save', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify(payload)
      });

      const resData = await res.json();
      if (!res.ok || !resData.success) {
        throw new Error(resData.error || 'Failed to initialize draft in database');
      }

      // Sync updated IDs
      if (resData.product?.id) {
        productForm.id = resData.product.id;
      }
      if (resData.variants && Array.isArray(resData.variants)) {
        variants = variants.map((v) => {
          const match = resData.variants.find((rv: any) => rv.sku === v.sku || rv.id === v.id);
          return match ? { ...v, id: match.id } : v;
        });
      }

      return true;
    } catch (err: any) {
      console.error('Draft save failed:', err);
      uiStore.addToast(err.message || 'Draft initialization error', 'error');
      return false;
    }
  }

  // Upload Images for a Variant
  async function handleFileUpload(files: FileList | File[], variantId: string) {
    if (!files || files.length === 0) return;

    const variant = variants.find(v => v.id === variantId);
    if (!variant) return;

    // Validate draft is in DB
    isUploading = true;
    uploadError = null;
    uploadProgress = 'Preparing draft for upload...';

    const draftReady = await ensureDraftInDatabase();
    if (!draftReady) {
      isUploading = false;
      uploadProgress = null;
      return;
    }

    // Refresh active variant with confirmed DB ID
    const updatedVariant = variants.find(v => v.id === variantId || v.sku === variant.sku);
    const confirmedVariantId = updatedVariant?.id || variant.id;

    const fileArray = Array.from(files);
    let uploadedCount = 0;

    for (let i = 0; i < fileArray.length; i++) {
      const file = fileArray[i];

      // Client-side file validation
      if (!file.type.startsWith('image/')) {
        uploadError = `File "${file.name}" is not an image. Only JPG, PNG, WEBP allowed.`;
        uiStore.addToast(uploadError, 'error');
        continue;
      }
      if (file.size > 15 * 1024 * 1024) {
        uploadError = `File "${file.name}" exceeds 15MB limit.`;
        uiStore.addToast(uploadError, 'error');
        continue;
      }

      uploadProgress = `Uploading ${i + 1} of ${fileArray.length}: ${file.name}...`;

      try {
        const formData = new FormData();
        formData.append('file', file);
        formData.append('product_id', productForm.id);
        formData.append('variant_id', confirmedVariantId!);
        formData.append('color_slug', updatedVariant?.color_slug || slugify(updatedVariant?.color_name || 'color'));
        formData.append('product_slug', slugify(productForm.slug));
        formData.append('alt_text', `${productForm.name} in ${updatedVariant?.color_name}`);

        const res = await fetch('/api/admin/products/upload-image', {
          method: 'POST',
          body: formData
        });

        const data = await res.json();
        if (!res.ok || !data.success) {
          throw new Error(data.error || `Upload failed for ${file.name}`);
        }

        // Add to local images list
        const newImg: DBProductImage = data.image;
        if (updatedVariant) {
          updatedVariant.images = [...(updatedVariant.images || []), newImg];
          variants = [...variants];
        }
        uploadedCount++;
      } catch (err: any) {
        console.error('Upload failed for file:', err);
        uploadError = err.message || 'Image upload failed';
        uiStore.addToast(uploadError, 'error');
      }
    }

    isUploading = false;
    uploadProgress = null;
    if (uploadedCount > 0) {
      uiStore.addToast(`Successfully uploaded ${uploadedCount} image(s) with tags & naming.`, 'success');
    }
  }

  // Delete Image
  async function handleDeleteImage(variantId: string, imageId: string, ikFileId?: string) {
    if (!confirm('Are you sure you want to delete this image?')) return;

    try {
      const res = await fetch('/api/admin/products/delete-image', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ imageId, imagekitFileId: ikFileId })
      });

      const data = await res.json();
      if (!res.ok || !data.success) {
        throw new Error(data.error || 'Failed to delete image');
      }

      // Update local state
      const variant = variants.find(v => v.id === variantId);
      if (variant) {
        variant.images = variant.images.filter(img => img.id !== imageId);
        // If the deleted one was primary, mark first remaining as primary
        if (variant.images.length > 0 && !variant.images.some(img => img.is_primary)) {
          variant.images[0].is_primary = true;
        }
        variants = [...variants];
      }

      uiStore.addToast('Image deleted.', 'info');
    } catch (err: any) {
      uiStore.addToast(err.message || 'Failed to delete image', 'error');
    }
  }

  // Set Primary Image
  async function handleSetPrimary(variantId: string, imageId: string) {
    const variant = variants.find(v => v.id === variantId);
    if (!variant) return;

    variant.images = variant.images.map(img => ({
      ...img,
      is_primary: img.id === imageId
    }));
    variants = [...variants];

    try {
      await fetch('/api/admin/products/reorder-images', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          variantId,
          imageOrders: variant.images.map((img, idx) => ({ id: img.id, position: idx, is_primary: img.id === imageId })),
          primaryImageId: imageId
        })
      });
      uiStore.addToast('Primary image updated.', 'success');
    } catch (e) {
      console.warn('Set primary warning:', e);
    }
  }

  // Drag-and-drop Image Reordering
  function handleDragStart(index: number) {
    draggedImageIndex = index;
  }

  function handleDragOver(e: DragEvent, targetIndex: number) {
    e.preventDefault();
  }

  async function handleDrop(targetIndex: number, variantId: string) {
    if (draggedImageIndex === null || draggedImageIndex === targetIndex) return;

    const variant = variants.find(v => v.id === variantId);
    if (!variant) return;

    const imagesList = [...variant.images];
    const [moved] = imagesList.splice(draggedImageIndex, 1);
    imagesList.splice(targetIndex, 0, moved);

    // Update positions
    const updatedImages = imagesList.map((img, idx) => ({
      ...img,
      position: idx
    }));

    variant.images = updatedImages;
    variants = [...variants];
    draggedImageIndex = null;

    // Persist new order
    try {
      await fetch('/api/admin/products/reorder-images', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          variantId,
          imageOrders: updatedImages.map(img => ({ id: img.id, position: img.position, is_primary: img.is_primary }))
        })
      });
    } catch (e) {
      console.warn('Reorder save warning:', e);
    }
  }

  // Validation before publishing
  interface ValidationItem {
    id: string;
    label: string;
    passed: boolean;
    errorText?: string;
  }

  const validationList = $derived.by<ValidationItem[]>(() => {
    const list: ValidationItem[] = [];

    // 1. Basic Info
    const hasName = Boolean(productForm.name.trim());
    const hasSlug = Boolean(productForm.slug.trim());
    const hasPrice = !isNaN(parseFloat(productForm.base_price)) && parseFloat(productForm.base_price) >= 0;
    list.push({
      id: 'basic-info',
      label: 'Product Title, Slug & Valid Base Price',
      passed: hasName && hasSlug && hasPrice,
      errorText: !hasName ? 'Product name is missing' : !hasSlug ? 'Product slug is missing' : !hasPrice ? 'Base price must be a valid number' : undefined
    });

    // 2. At least 1 variant
    const hasVariants = variants.length >= 1;
    list.push({
      id: 'has-variants',
      label: 'At least one color variant defined',
      passed: hasVariants,
      errorText: !hasVariants ? 'You must create at least 1 color variant.' : undefined
    });

    // 3. Exactly 1 default variant
    const defaultCount = variants.filter(v => v.is_default).length;
    list.push({
      id: 'one-default',
      label: 'Exactly one default variant selected',
      passed: defaultCount === 1,
      errorText: defaultCount === 0 ? 'Please choose one variant as the default.' : defaultCount > 1 ? 'Multiple default variants are selected.' : undefined
    });

    // 4. Unique SKUs
    const skus = variants.map(v => v.sku.trim().toUpperCase()).filter(Boolean);
    const uniqueSkus = new Set(skus);
    const allSkusFilled = variants.every(v => Boolean(v.sku.trim()));
    const skusUnique = uniqueSkus.size === variants.length && allSkusFilled;
    list.push({
      id: 'unique-skus',
      label: 'All variants have unique SKU codes',
      passed: skusUnique,
      errorText: !allSkusFilled ? 'One or more variants are missing SKUs.' : !skusUnique ? 'Duplicate SKUs found. Each SKU must be unique.' : undefined
    });

    // 5. Images per variant
    const allHaveImages = variants.every(v => v.images && v.images.length > 0);
    list.push({
      id: 'images-per-variant',
      label: 'Every variant has at least one image',
      passed: allHaveImages,
      errorText: !allHaveImages ? 'Some variants do not have any uploaded images.' : undefined
    });

    // 6. Sizes defined
    const hasSizes = Array.isArray(productForm.sizes) && productForm.sizes.length > 0;
    list.push({
      id: 'has-sizes',
      label: 'At least one shoe size configured',
      passed: hasSizes,
      errorText: !hasSizes ? 'Please select at least one shoe size for this product.' : undefined
    });

    return list;
  });

  const allValidForPublish = $derived(validationList.every(item => item.passed));

  // Commit / Save Product
  async function commitProduct(targetStatus: 'draft' | 'published') {
    if (targetStatus === 'published' && !allValidForPublish) {
      uiStore.addToast('Please resolve validation errors before publishing.', 'error');
      return;
    }

    isSaving = true;

    try {
      const payload = {
        product: {
          id: productForm.id || undefined,
          name: productForm.name.trim(),
          slug: slugify(productForm.slug),
          brand: productForm.brand.trim(),
          category: productForm.category,
          base_price: parseFloat(productForm.base_price) || 0,
          compare_at_price: productForm.compare_at_price ? parseFloat(productForm.compare_at_price) : null,
          sizes: productForm.sizes,
          description: productForm.description,
          status: targetStatus
        },
        variants: variants.map((v, i) => ({
          id: v.id,
          sku: v.sku.trim().toUpperCase(),
          color_name: v.color_name.trim(),
          color_slug: slugify(v.color_name),
          color_hex: v.color_hex,
          attributes: { ...v.attributes, size_stock: v.size_stock },
          price_override: v.price_override ? parseFloat(String(v.price_override)) : null,
          compare_at_price: v.compare_at_price ? parseFloat(String(v.compare_at_price)) : null,
          stock_quantity: Number(v.stock_quantity || 0),
          is_default: Boolean(v.is_default),
          position: i
        })),
        images: variants.flatMap(v => (v.images || []).map((img, imgIdx) => ({
          id: img.id,
          variant_id: v.id,
          imagekit_file_id: img.imagekit_file_id,
          image_url: img.image_url,
          file_name: img.file_name,
          alt_text: img.alt_text,
          position: img.position !== undefined ? img.position : imgIdx,
          is_primary: Boolean(img.is_primary)
        })))
      };

      const res = await fetch('/api/admin/products/save', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify(payload)
      });

      const result = await res.json();

      if (!res.ok || !result.success) {
        throw new Error(result.error || 'Failed to commit product');
      }

      uiStore.addToast(
        targetStatus === 'published' 
          ? '🎉 Product published successfully!' 
          : 'Product draft saved successfully.', 
        'success'
      );

      goto('/admin/products');
    } catch (err: any) {
      console.error('Commit product failed:', err);
      uiStore.addToast(err.message || 'Error saving product', 'error');
    } finally {
      isSaving = false;
    }
  }

  // Active variant tab object in step 3
  const currentTabVariant = $derived(variants.find(v => v.id === activeVariantTabId) || variants[0]);
