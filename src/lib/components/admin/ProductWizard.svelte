  async function loadExistingProduct(id: string) {
    try {
      const { data: prod, error: pErr } = await supabase
        .from('products')
        .select('*')
        .eq('id', id)
        .single();

      if (pErr || !prod) {
        uiStore.addToast('Could not load product details', 'error');
        return;
      }

      const { data: dbVars, error: vErr } = await supabase
        .from('product_variants')
        .select('*, images:product_images(*)')
        .eq('product_id', id)
        .order('position', { ascending: true });

      const loadedVariants: LocalVariant[] = (dbVars || []).map((v: any, index: number) => ({
        id: v.id,
        sku: v.sku,
        color_name: v.color_name,
        color_slug: v.color_slug,
        color_hex: v.color_hex,
        attributes: v.attributes || {},
        size_stock: v.attributes?.size_stock || {},
        price_override: v.price_override ? String(v.price_override) : '',
        compare_at_price: v.compare_at_price ? String(v.compare_at_price) : '',
        stock_quantity: v.stock_quantity || 0,
        is_default: v.is_default,
        position: v.position ?? index,
        images: (v.images || []).sort((a: any, b: any) => (a.position ?? 0) - (b.position ?? 0))
      }));

      populateInitialData({
        ...prod,
        variants: loadedVariants as any
      });
    } catch (e: any) {
      console.error('Error loading product:', e);
      uiStore.addToast(e.message || 'Failed to load product', 'error');
    }
  }

