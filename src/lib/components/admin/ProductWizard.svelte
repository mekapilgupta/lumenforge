    const defaultColor = QUICK_PALETTE[variants.length % QUICK_PALETTE.length];
    const slugCode = (productForm.slug || 'FT').toUpperCase().slice(0, 8);
    const colorCode = slugify(defaultColor.name).toUpperCase().slice(0, 4);
    const newSku = `${slugCode}-${colorCode}-${variants.length + 1}`;

